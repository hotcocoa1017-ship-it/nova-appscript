create or replace function nova_private.nova_archive_prune_failure_notification_trigger()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_user record;
  v_new_failed boolean := upper(coalesce(new.status,'')) = 'FAILED';
  v_old_failed boolean := case when tg_op='UPDATE' then upper(coalesce(old.status,'')) = 'FAILED' else false end;
begin
  if not v_new_failed or v_old_failed then return new; end if;
  for v_user in select employee_no from public.nova_users where enabled = true and upper(coalesce(role,'')) = 'ADMIN' loop
    perform nova_private.nova_notification_emit(
      v_user.employee_no,'ARCHIVE_ALERT','Archive Prune 실패',
      concat_ws(' · ', nullif(new.business_date::text,''), nullif(new.site,''), nullif(new.message,'')),
      new.site,'','ARCHIVE_PRUNE',new.run_id::text,'HIGH',
      jsonb_build_object('route','archive','runId',new.run_id),
      'ARCHIVE_PRUNE_FAILED|' || new.run_id::text || '|' || v_user.employee_no
    );
  end loop;
  return new;
end;
$function$;
revoke all on function nova_private.nova_archive_prune_failure_notification_trigger() from public, anon, authenticated;
drop trigger if exists nova_archive_prune_failure_notification_trg on public.nova_archive_prune_runs;
create trigger nova_archive_prune_failure_notification_trg
after insert or update of status on public.nova_archive_prune_runs
for each row execute function nova_private.nova_archive_prune_failure_notification_trigger();

