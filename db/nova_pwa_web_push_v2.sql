create or replace function nova_private.nova_notification_web_push_trigger()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_token text;
  v_request_id bigint;
begin
  if not exists (
    select 1 from public.nova_push_subscriptions s
    where s.employee_no=new.recipient_employee_no and s.enabled=true
  ) then
    return new;
  end if;

  select s.decrypted_secret into v_token
  from vault.decrypted_secrets s
  where s.name='nova_web_push_dispatch_token_v2'
  limit 1;
  if coalesce(v_token,'')='' then return new; end if;

  -- Push is deliberately async/best-effort: it must never block the core NOVA write path.
  begin
    select net.http_post(
      url := 'https://evoetxfjmkkjptucwxsv.supabase.co/functions/v1/nova-web-push-v2',
      body := jsonb_build_object('notificationId',new.notification_id),
      params := '{}'::jsonb,
      headers := jsonb_build_object(
        'Content-Type','application/json',
        'X-NOVA-Web-Push-Token',v_token
      ),
      timeout_milliseconds := 15000
    ) into v_request_id;
  exception when others then
    null;
  end;
  return new;
end;
$function$;
revoke all on function nova_private.nova_notification_web_push_trigger() from public, anon, authenticated;

drop trigger if exists nova_notification_web_push_trg on public.nova_notifications;
create trigger nova_notification_web_push_trg
after insert on public.nova_notifications
for each row execute function nova_private.nova_notification_web_push_trigger();