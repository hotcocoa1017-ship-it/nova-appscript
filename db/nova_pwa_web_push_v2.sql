-- NOVA PWA + Web Push V2
-- Applied to nova-realtime on 2026-09-06.
-- Secret VALUES are intentionally omitted from source control.
-- Required Vault secret names:
--   nova_web_push_vapid_private_v2
--   nova_web_push_dispatch_token_v2

create table if not exists public.nova_push_subscriptions (
  subscription_id uuid primary key default gen_random_uuid(),
  employee_no text not null,
  endpoint text not null unique,
  p256dh text not null,
  auth_secret text not null,
  user_agent text not null default '',
  platform text not null default '',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  last_success_at timestamptz null,
  last_failure_at timestamptz null,
  failure_count integer not null default 0,
  last_error text not null default ''
);

create index if not exists nova_push_subscriptions_employee_enabled_idx
  on public.nova_push_subscriptions (employee_no, enabled, updated_at desc);

alter table public.nova_push_subscriptions enable row level security;
revoke all on table public.nova_push_subscriptions from public, anon, authenticated;
grant select, insert, update, delete on table public.nova_push_subscriptions to authenticated;

drop policy if exists "nova push subscriptions read own" on public.nova_push_subscriptions;
create policy "nova push subscriptions read own"
on public.nova_push_subscriptions for select to authenticated
using (employee_no = coalesce(((select auth.jwt()) ->> 'employee_no'), ''));

drop policy if exists "nova push subscriptions insert own" on public.nova_push_subscriptions;
create policy "nova push subscriptions insert own"
on public.nova_push_subscriptions for insert to authenticated
with check (employee_no = coalesce(((select auth.jwt()) ->> 'employee_no'), ''));

drop policy if exists "nova push subscriptions update own" on public.nova_push_subscriptions;
create policy "nova push subscriptions update own"
on public.nova_push_subscriptions for update to authenticated
using (employee_no = coalesce(((select auth.jwt()) ->> 'employee_no'), ''))
with check (employee_no = coalesce(((select auth.jwt()) ->> 'employee_no'), ''));

drop policy if exists "nova push subscriptions delete own" on public.nova_push_subscriptions;
create policy "nova push subscriptions delete own"
on public.nova_push_subscriptions for delete to authenticated
using (employee_no = coalesce(((select auth.jwt()) ->> 'employee_no'), ''));

create or replace function nova_private.nova_push_subscription_claim_trigger()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_employee_no text := coalesce(((select auth.jwt()) ->> 'employee_no'), '');
begin
  if coalesce(v_employee_no,'') = '' or new.employee_no <> v_employee_no then
    raise exception 'push subscription employee mismatch';
  end if;
  -- A shared/reused phone endpoint can belong to only the currently signed-in employee.
  delete from public.nova_push_subscriptions s
  where s.endpoint = new.endpoint
    and s.employee_no <> new.employee_no;
  new.updated_at := now();
  new.last_seen_at := now();
  return new;
end;
$function$;
revoke all on function nova_private.nova_push_subscription_claim_trigger() from public, anon, authenticated;

drop trigger if exists nova_push_subscription_claim_trg on public.nova_push_subscriptions;
create trigger nova_push_subscription_claim_trg
before insert on public.nova_push_subscriptions
for each row execute function nova_private.nova_push_subscription_claim_trigger();

